"""Derive the existing K family from brand/klados-mark.svg; no external services."""

import argparse
import base64
import sys
import xml.etree.ElementTree as ET
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NS = "http://www.w3.org/2000/svg"
ET.register_namespace("", NS)


def outputs():
    canonical = (ROOT / "brand/klados-mark.svg").read_text(encoding="utf-8")
    mark = ET.fromstring(canonical)
    paths = mark.findall("{" + NS + "}path")
    if len(paths) != 1 or mark.attrib["viewBox"] != "0 0 80 80":
        raise ValueError("Expected the reviewed single-path K")
    shape = ET.tostring(paths[0], encoding="unicode").replace(f' xmlns="{NS}"', "")
    sys.path.insert(0, str(ROOT))
    from arena.visual_assets import RESOURCES

    font = base64.b64encode(RESOURCES["space-grotesk.ttf"][1]).decode("ascii")
    license_text = (ROOT / "docs/font-licenses/spacegrotesk-OFL.txt").read_text(encoding="utf-8")
    typography = (
        "<metadata>"
        + escape(license_text)
        + "</metadata><style>@font-face{font-family:Brand;src:url(data:font/ttf;base64,"
        + font
        + ") format('truetype')}text{font-family:Brand,sans-serif}</style>"
    )

    def svg(width, height, content, title="Klados World - A world for agents."):
        return (
            f'<svg xmlns="{NS}" width="{width}" height="{height}" '
            f'viewBox="0 0 {width} {height}" role="img" aria-labelledby="title">'
            f'<title id="title">{title}</title>{content}</svg>\n'
        )

    favicon = (
        f'<svg xmlns="{NS}" viewBox="0 0 80 80" role="img" aria-labelledby="title">'
        '<title id="title">Klados World</title><rect width="80" height="80" rx="14" '
        f'fill="#0B0F14"/>{shape}</svg>\n'
    )
    avatar = svg(
        1024,
        1024,
        '<rect width="1024" height="1024" rx="180" fill="#0B0F14"/>'
        '<circle cx="512" cy="512" r="420" fill="#082225" stroke="#00CC96" '
        'stroke-opacity=".25" stroke-width="2"/>'
        f'<g transform="translate(27 112) scale(10)">{shape}</g>',
    )

    def card(width, height, mark_x, text_x):
        return svg(
            width,
            height,
            typography
            + f'<rect width="{width}" height="{height}" fill="#0B0F14"/>'
            + f'<path d="M0 {height - 50}H{width}" stroke="#00CC96" stroke-opacity=".3"/>'
            + f'<circle cx="{width - 80}" cy="80" r="240" fill="#00CC96" fill-opacity=".035"/>'
            + f'<g transform="translate({mark_x} {height / 2 - 128}) scale(3.2)">{shape}</g>'
            + f'<text x="{text_x}" y="{height / 2 - 12}" fill="#E6E9ED" '
            'font-size="40" letter-spacing="5">KLADOS WORLD</text>'
            + f'<text x="{text_x}" y="{height / 2 + 58}" fill="#00CC96" '
            'font-size="44">A world for agents.</text>'
            + f'<path d="M{text_x} {height / 2 + 96}h70" stroke="#F5C46B" stroke-width="3"/>',
        )

    result = {
        "arena/static/favicon.svg": favicon,
        "brand/klados-avatar.svg": avatar,
        "brand/klados-social-card.svg": card(1200, 630, 70, 420),
        "brand/klados-x-header.svg": card(1500, 500, 290, 640),
    }
    packed = {"mark.svg": ("image/svg+xml", canonical.encode("utf-8"))}
    png = ROOT / "brand/klados-social-card.png"
    if png.exists():
        packed["social-card.png"] = ("image/png", png.read_bytes())
    module = "# Generated by scripts/build_brand_assets.py from brand/klados-mark.svg.\n"
    module += "# Embedded font license: docs/font-licenses/spacegrotesk-OFL.txt.\n"
    module += f"FAVICON = {favicon!r}\nRESOURCES = {{\n"
    for name, (mime, data) in packed.items():
        module += f"    {name!r}: ({mime!r}, {data!r}),\n"
    result["arena/brand_assets.py"] = module + "}\n"
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument(
        "--render", action="store_true", help="Export portable PNGs in local Chromium"
    )
    parser.add_argument("--browser")
    args = parser.parse_args()
    if args.check and args.render:
        parser.error("check cannot write rendered files")
    for name, data in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != data:
                raise SystemExit("Stale generated asset: " + name)
        else:
            path.write_text(data, encoding="utf-8", newline="\n")
    if args.render:
        if not args.browser:
            parser.error("render requires --browser")
        from playwright.sync_api import sync_playwright

        with sync_playwright() as playwright:
            browser = playwright.chromium.launch(executable_path=args.browser, headless=True)
            page = browser.new_page(viewport={"width": 1600, "height": 1200}, device_scale_factor=1)
            for filename in ("klados-avatar", "klados-social-card", "klados-x-header"):
                markup = (ROOT / f"brand/{filename}.svg").read_text(encoding="utf-8")
                page.set_content(markup)
                page.evaluate("document.fonts.ready")
                page.locator("svg").screenshot(
                    path=str(ROOT / f"brand/{filename}.png"), omit_background=True
                )
            browser.close()
        for name, data in outputs().items():
            (ROOT / name).write_text(data, encoding="utf-8", newline="\n")
    print("PASS: canonical K derivatives " + ("verified" if args.check else "generated"))


if __name__ == "__main__":
    main()
